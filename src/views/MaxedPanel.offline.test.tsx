// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { refreshCatalog } from '../catalog';
import { defaultState } from '../defaults';
import { StoreProvider } from '../store';
import { PlanProvider } from '../planner';
import CardsView from './CardsView';
import { dayLabel } from '../ui';

// Its own file, so catalog.ts starts with no card list downloaded: a test that loaded it would leave it cached.
beforeEach(() => {
  vi.stubGlobal('fetch', () => Promise.reject(new Error('offline')));
});
afterEach(() => {
  cleanup();
  localStorage.clear();
  vi.unstubAllGlobals();
});

describe("Cards: the Maxed page when MK Mobile Base's list doesn't load", () => {
  // Generated by /ship test coverage audit on 2026-10-18; changed by /ship review fixes on 2026-10-18
  // Value: protects=a failed catalog load says completion can't be worked out instead of loading forever, the record
  // still lists its cards, and Try again loads it once it's back; fails_when=the load's error handler goes (Loading…
  // stays), the list waits on the catalog, or Try again doesn't fetch again; why_new=the other Maxed page tests all load
  // the catalog; seam=fetch stubbed to fail, then to serve a list; no_claim=pull to refresh
  it('says completion is unavailable, still lists the record, and tries again', async () => {
    const s = defaultState();
    s.maxed = [{ name: 'Kori Blade', rarityId: 'epic', at: '2026-10-18' }];
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    render(
      <StoreProvider>
        <PlanProvider>
          <CardsView sub="maxed" onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>,
    );
    expect(await screen.findByText(/card list didn't load, so completion can't be worked out yet/)).not.toBeNull();
    expect([screen.queryByText(/Loading MK Mobile Base/), screen.queryByText(/of every card MK Mobile Base lists/)]).toEqual([null, null]);
    expect([screen.getByText('Kori Blade') != null, screen.queryByText(`maxed ${dayLabel('2026-10-18', new Date())}`) != null]).toEqual([true, true]);
    const items = [{ kind: 'equipment', name: 'Kori Blade', rarity: 'epic', slug: 'kori', image: 'kori.webp' }];
    vi.stubGlobal('fetch', () => Promise.resolve(new Response(JSON.stringify({ items }))));
    fireEvent.click(screen.getByRole('button', { name: 'Try again' }));
    expect(await screen.findByText(/of every card MK Mobile Base lists: 1 of 1 maxed/)).not.toBeNull();
    // Extended on 2026-10-25 (/ship review, run 16, maintainability)
    // Value: protects=the Maxed page reads a catalog fetched again while it's open (pull to refresh, or coming back after
    // an hour), so completion counts the daily deploy's new cards; fails_when=it keeps the copy it read when it opened;
    // why_new=review (maintainability): App and the card list re-read it, the Maxed page didn't; seam=fetch stubbed,
    // refreshCatalog called as a pull does; no_claim=none beyond protects
    vi.stubGlobal('fetch', () => Promise.resolve(new Response(JSON.stringify({ items: [...items, { ...items[0], name: 'Kitana Fan', slug: 'fan' }] }))));
    await act(() => refreshCatalog());
    expect(await screen.findByText(/of every card MK Mobile Base lists: 1 of 2 maxed/)).not.toBeNull();
  });
});
