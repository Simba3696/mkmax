// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { defaultState } from '../defaults';
import { StoreProvider, useStore } from '../store';
import { PlanProvider } from '../planner';
import { SyncLoop } from '../syncLoop';
import type { CatalogItem } from '../catalog';
import CardsView from './CardsView';
import { dayLabel } from '../ui';

/** Hands the store, as each render sees it, to the test, as any view would use it. */
function Grab({ onRender }: { onRender: (store: ReturnType<typeof useStore>) => void }) {
  onRender(useStore());
  return null;
}

const item = (kind: CatalogItem['kind'], name: string, rarity: string): CatalogItem => ({ kind, name, rarity, slug: name, image: `${name}.webp` });
/** What Remove reads once tapped, until a second tap confirms it (ConfirmButton). */
const ARMED = 'Tap again to confirm';
const ITEMS = [item('character', 'Scorpion MK2 Movie', 'diamond'), item('character', 'Sub-Zero MK1', 'diamond'), item('equipment', 'Kori Blade', 'epic')];

beforeEach(() => {
  // The catalog loads from the app's own catalog.json; the event schedule isn't needed here.
  vi.stubGlobal('fetch', (url: string) =>
    String(url).includes('catalog.json') ? Promise.resolve(new Response(JSON.stringify({ items: ITEMS }))) : Promise.reject(new Error('offline')),
  );
});
afterEach(() => {
  cleanup();
  localStorage.clear();
  vi.unstubAllGlobals();
  vi.restoreAllMocks();
});

describe('Cards: the Maxed page', () => {
  let update!: ReturnType<typeof useStore>['update'];
  let lastUndo: ReturnType<typeof useStore>['lastUndo'] = null;
  function renderMaxed(tweak: (s: ReturnType<typeof defaultState>) => void) {
    const s = defaultState();
    tweak(s);
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    render(
      <StoreProvider>
        <PlanProvider>
          <Grab onRender={(store) => ((update = store.update), (lastUndo = store.lastUndo))} />
          <CardsView sub="maxed" onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>,
    );
    return vi.spyOn(SyncLoop.prototype, 'nextStamp');
  }
  const saved = () => JSON.parse(localStorage.getItem('mkmax:v1')!);

  // Value: protects=the Maxed page shows completion per rarity against MK Mobile Base's list, overall, and the record
  // with its dates; fails_when=a figure counts cards the catalog doesn't list under that rarity, or the list or dates
  // don't show; why_new=the Maxed page is new; seam=fetch stubbed with a small catalog; no_claim=the counting rules
  // (catalog.test.ts)
  it('shows completion and the maxed cards', async () => {
    renderMaxed((s) => (s.maxed = [{ name: 'Scorpion, MKII Movie', rarityId: 'diamond', at: '2026-10-18' }]));
    expect(await screen.findByText(/of every card MK Mobile Base lists: 1 of 3 maxed/)).not.toBeNull();
    expect(screen.getByText('50%')).not.toBeNull(); // Diamond: 1 of 2
    expect([screen.getByText('Scorpion, MKII Movie') != null, screen.queryByText(`maxed ${dayLabel('2026-10-18', new Date())}`) != null]).toEqual([true, true]);
  });

  // Generated by /ship test coverage audit on 2026-10-18
  // Value: protects=each maxed card shows its art from MK Mobile Base's list (the record keeps only a name and rarity),
  // matched by name in any order, and one the list doesn't have shows its initials; fails_when=the row's art lookup goes
  // or matches the wrong card, so every row shows initials or another card's art; why_new=the other tests read text
  // only; seam=fetch stubbed with a small catalog; no_claim=broken image URLs (ui.test.tsx)
  it('shows card art from MK Mobile Base for each maxed card', async () => {
    renderMaxed((s) => (s.maxed = [{ name: 'Scorpion, MKII Movie', rarityId: 'diamond' }, { name: 'Noob Saibot, MK1', rarityId: 'diamond' }]));
    await screen.findByText(/of every card MK Mobile Base lists/);
    const art = (name: string) => screen.getByText(name).closest('div')!.parentElement!.parentElement!.firstElementChild!;
    expect([art('Scorpion, MKII Movie').getAttribute('src'), art('Noob Saibot, MK1').tagName, art('Noob Saibot, MK1').textContent]).toEqual(['Scorpion MK2 Movie.webp', 'SPAN', 'NS']);
  });

  // Generated by /ship review fixes on 2026-10-18
  // Value: protects=the page names record entries MK Mobile Base doesn't list under their rarity, and doesn't count them;
  // fails_when=the note goes or names the wrong cards; why_new=catalog.test.ts covers completion().unlisted, not the page;
  // seam=fetch stubbed with a small catalog; no_claim=the counting rules
  it("names maxed cards MK Mobile Base doesn't list under their rarity", async () => {
    renderMaxed((s) => (s.maxed = [{ name: 'Noob Saibot, MK1', rarityId: 'diamond' }, { name: 'Sub-Zero, MK1', rarityId: 'diamond' }]));
    expect(await screen.findByText(/of every card MK Mobile Base lists: 1 of 3 maxed/)).not.toBeNull();
    expect(screen.queryByText("1 maxed card isn't on MK Mobile Base's list under its rarity yet, so it isn't counted: Noob Saibot, MK1.")).not.toBeNull();
  });

  // Changed by /ship review fixes on 2026-10-18
  // Value: protects=Remove (two taps, as Delete on cards) takes one card off the record with an Undo, finds it by name
  // when a sync has shifted the list, and saves nothing for one already removed; fails_when=Remove takes the entry at
  // the tapped place, or stamps a save for nothing; why_new=the Maxed page is new; seam=the armed button's handler as the
  // screen had it before the sync, a grabbed update stands in for the sync, SyncLoop.nextStamp spied; no_claim=a real sync
  it('removes a card with Undo, by name after a sync, and saves nothing for one already removed', () => {
    const stamps = renderMaxed((s) => (s.maxed = [{ name: 'Kori Blade', rarityId: 'epic' }, { name: 'Sub-Zero, MK1', rarityId: 'diamond' }]));
    const handler = (b: HTMLElement) => (b as unknown as Record<string, { onClick: () => void }>)[Object.keys(b).find((k) => k.startsWith('__reactProps$'))!].onClick;
    // Listed by rarity: Sub-Zero (Diamond) first, then Kori Blade (Epic). The first tap arms it.
    fireEvent.click(screen.getAllByRole('button', { name: 'Remove' })[1]);
    const onClick = handler(screen.getByRole('button', { name: ARMED }));
    // A sync puts a card ahead of Kori Blade: the tap still removes Kori Blade, not the card now in its place.
    act(() => update((d) => void d.maxed!.unshift({ name: 'Jade, Lizard', rarityId: 'diamond' })));
    act(() => onClick());
    expect([saved().maxed.map((m: { name: string }) => m.name), lastUndo?.label]).toEqual([['Jade, Lizard', 'Sub-Zero, MK1'], 'Removed Kori Blade from Maxed']);
    stamps.mockClear();
    act(() => onClick());
    expect(stamps).not.toHaveBeenCalled(); // gone already: nothing saved
  });

  // Generated by /ship test coverage audit on 2026-10-18
  // Value: protects=the Maxed page redraws when the record changes under it: a new day on an entry shows, and a removed
  // entry leaves the list and the heading's count; fails_when=useSame's key misses the day (or any change), so the page
  // keeps the record as first drawn while the save moves on; why_new=every other test reads a record that doesn't change
  // after the page is drawn; seam=a grabbed update stands in for a sync; no_claim=the completion figures redrawing
  it('redraws the record when a sync changes a day and removes an entry', () => {
    renderMaxed((s) => (s.maxed = [{ name: 'Kori Blade', rarityId: 'epic', at: '2026-10-01' }, { name: 'Sub-Zero, MK1', rarityId: 'diamond' }]));
    const count = () => screen.getByRole('heading', { name: /^Maxed cards/ }).querySelector('span')!.textContent;
    expect([count(), screen.queryByText(`maxed ${dayLabel('2026-10-05', new Date())}`)]).toEqual(['2', null]);
    // The day alone changes first, so a key that only notices entries coming and going doesn't pass.
    act(() => update((d) => void (d.maxed!.find((m) => m.name === 'Kori Blade')!.at = '2026-10-05')));
    expect(screen.queryByText(`maxed ${dayLabel('2026-10-05', new Date())}`)).not.toBeNull();
    act(() => update((d) => void (d.maxed = d.maxed!.filter((m) => m.name !== 'Sub-Zero, MK1'))));
    expect([count(), screen.queryByText('Sub-Zero, MK1'), screen.queryByText(`maxed ${dayLabel('2026-10-05', new Date())}`) != null]).toEqual(['1', null, true]);
  });

  // Generated by /ship test coverage audit on 2026-10-18
  // Value: protects=Paste maxed cards' Add is greyed out and reads "Add maxed cards" while the box is empty, and plain
  // names go under the rarity picked in "Rarity for plain names"; fails_when=the pick is ignored (plain names saved under
  // the first rarity), or an empty box can be added; why_new=the paste tests above only use lines that name their rarity;
  // seam=none; no_claim=a rarity a sync removed after the pick
  it('greys out Add for an empty box, and saves plain names under the rarity picked', () => {
    renderMaxed(() => {});
    fireEvent.click(screen.getByRole('button', { name: 'Paste maxed cards…' }));
    expect((screen.getByRole('button', { name: 'Add maxed cards' }) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.change(screen.getByLabelText('Rarity for plain names'), { target: { value: 'epic' } });
    fireEvent.change(screen.getByLabelText('Maxed cards'), { target: { value: 'Kori Blade' } });
    fireEvent.click(screen.getByRole('button', { name: 'Add 1' }));
    expect(saved().maxed).toEqual([{ name: 'Kori Blade', rarityId: 'epic' }]);
  });

  // Generated by /ship review fixes on 2026-10-18
  // Value: protects=search lists only matching entries, says when none match, and an empty record says so with no search
  // box; fails_when=the filter or either message is lost; why_new=no test typed in the search; seam=none; no_claim=sorting
  it('searches the record and says when nothing is there', () => {
    renderMaxed((s) => (s.maxed = [{ name: 'Kori Blade', rarityId: 'epic' }, { name: 'Sub-Zero, MK1', rarityId: 'diamond' }]));
    // The card list keeps its own search box on the page, hidden.
    const page = () => within(screen.getByRole('heading', { name: /^Maxed cards/ }).closest('section')!);
    const search = page().getByPlaceholderText('Search…');
    fireEvent.change(search, { target: { value: 'kori' } });
    expect([screen.queryByText('Kori Blade') != null, screen.queryByText('Sub-Zero, MK1')]).toEqual([true, null]);
    fireEvent.change(search, { target: { value: 'nobody' } });
    expect(screen.queryByText('No maxed cards match.')).not.toBeNull();
    cleanup();
    renderMaxed(() => {});
    expect([screen.queryByText('No maxed cards yet.') != null, page().queryByPlaceholderText('Search…')]).toEqual([true, null]);
  });

  // Value: protects=Paste maxed cards adds new ones once, skips cards still in the card list (not maxed) and ones already
  // on the record, with an Undo; fails_when=a card still being maxed is recorded as maxed, or one is doubled;
  // why_new=the Maxed page is new; seam=none; no_claim=the list format (cardList.test.ts)
  it('adds pasted maxed cards, skipping ones still in the list or already recorded', () => {
    renderMaxed((s) => {
      s.cards = [{ id: 'sz', name: 'Sub-Zero, MK1', rarityId: 'diamond', fusion: 4, guest: false }];
      s.maxed = [{ name: 'Scorpion, MKII Movie', rarityId: 'diamond' }];
    });
    fireEvent.click(screen.getByRole('button', { name: 'Paste maxed cards…' }));
    fireEvent.change(screen.getByLabelText('Maxed cards'), { target: { value: 'Sub-Zero MK1\nScorpion MK2 Movie\nKori Blade - Epic' } });
    expect(screen.queryByText('New: 1 · skipping 1 already on Maxed (Scorpion MK2 Movie) · skipping 1 still in your card list, so not maxed yet (Sub-Zero MK1)')).not.toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Add 1' }));
    expect([saved().maxed.map((m: { name: string }) => m.name), lastUndo?.label]).toEqual([['Scorpion, MKII Movie', 'Kori Blade'], 'Added 1 to Maxed']);
  });

  // Generated by /ship test coverage audit on 2026-10-18
  // Value: protects=Paste maxed cards' Add skips a card a sync put back in the card list after the list was read, saving
  // nothing when none are left; fails_when=add() trusts the list as drawn, so a card still being fused is recorded maxed;
  // why_new=the test above has the card listed from the start; seam=a grabbed update stands in for the sync,
  // SyncLoop.nextStamp spied; no_claim=a real sync, a rarity a sync removed
  it('records nothing for a pasted card a sync put back in the list', () => {
    const stamps = renderMaxed(() => {});
    fireEvent.click(screen.getByRole('button', { name: 'Paste maxed cards…' }));
    fireEvent.change(screen.getByLabelText('Maxed cards'), { target: { value: 'Kori Blade - Epic' } });
    const add = screen.getByRole('button', { name: 'Add 1' });
    act(() => {
      update((d) => void d.cards.push({ id: 'kori', name: 'Kori Blade', rarityId: 'epic', fusion: 1, guest: false }));
      add.click();
    });
    expect([saved().maxed, stamps.mock.calls.length]).toEqual([[], 1]); // the sync stand-in only
    expect((screen.getByLabelText('Maxed cards') as HTMLTextAreaElement).value).toBe('Kori Blade - Epic');
  });

  // Generated by /ship review fixes on 2026-10-18
  // Value: protects=Paste maxed cards' Add records nothing under a rarity a sync removed after the list was read;
  // fails_when=entries are saved under a rarity that no longer exists (no badge, counted as unlisted); why_new=the test
  // above covers a card put back in the list, not a removed rarity; seam=a grabbed update stands in for the sync,
  // SyncLoop.nextStamp spied; no_claim=a real sync
  it('records nothing for a pasted card whose rarity a sync removed', () => {
    const stamps = renderMaxed(() => {});
    fireEvent.click(screen.getByRole('button', { name: 'Paste maxed cards…' }));
    fireEvent.change(screen.getByLabelText('Maxed cards'), { target: { value: 'Kori Blade - Epic' } });
    const add = screen.getByRole('button', { name: 'Add 1' });
    act(() => {
      update((d) => void (d.rarities = d.rarities.filter((r) => r.id !== 'epic')));
      add.click();
    });
    expect([saved().maxed, stamps.mock.calls.length]).toEqual([[], 1]); // the sync stand-in only
  });
});
