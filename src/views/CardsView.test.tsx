// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { defaultState } from '../defaults';
import { StoreProvider, useStore } from '../store';
import { PlanProvider } from '../planner';
import { SyncLoop } from '../syncLoop';
import CardsView from './CardsView';

/** Hands the store, as each render sees it, to the test, as any view would use it. */
function Grab({ onRender }: { onRender: (store: ReturnType<typeof useStore>) => void }) {
  onRender(useStore());
  return null;
}

beforeEach(() => {
  // The event schedule isn't needed here; keep the test off the network.
  vi.stubGlobal('fetch', () => Promise.reject(new Error('offline')));
});
afterEach(() => {
  cleanup();
  localStorage.clear();
  vi.unstubAllGlobals();
  vi.restoreAllMocks();
});

describe('Cards: Fusion Up Kards', () => {
  // Value: protects=Use N kards fuses one step, and a tap with too few kards left saves nothing; fails_when=the button's
  // noChange check is flipped (no tap ever fuses) or dropped (a tap that does nothing still stamps the save); why_new=
  // review (testing: only the Plan's copy of this line was tested); seam=SyncLoop.nextStamp spied to count saves;
  // no_claim=the Plan's button (PlanView.test.tsx)
  it('fuses once with Use N kards, and a second tap with no kards left saves nothing', () => {
    const s = defaultState();
    s.rarities.find((r) => r.id === 'diamond')!.fusionUpKards = 1;
    s.cards = [{ id: 'scorpion', name: 'Scorpion', rarityId: 'diamond', fusion: 4, guest: false }];
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    render(
      <StoreProvider>
        <PlanProvider>
          <CardsView sub="cards" onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>,
    );
    const stamps = vi.spyOn(SyncLoop.prototype, 'nextStamp');
    const use = screen.getByRole('button', { name: 'Use 1 kard' });
    // Both taps land before React draws again, so the second still shows the kard the first used.
    act(() => {
      use.click();
      use.click();
    });
    const saved = JSON.parse(localStorage.getItem('mkmax:v1')!);
    expect(saved.cards[0].fusion).toBe(5);
    expect(saved.rarities.find((r: { id: string }) => r.id === 'diamond').fusionUpKards).toBe(0);
    expect(stamps).toHaveBeenCalledTimes(1);
  });
});

describe('Cards: taps on a screen a sync has changed', () => {
  let update!: ReturnType<typeof useStore>['update'];
  function renderCards(fusion: number, kards: number) {
    const s = defaultState();
    s.rarities.find((r) => r.id === 'diamond')!.fusionUpKards = kards;
    s.cards = [{ id: 'scorpion', name: 'Scorpion', rarityId: 'diamond', fusion, guest: false }];
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    render(
      <StoreProvider>
        <PlanProvider>
          <Grab onRender={(store) => (update = store.update)} />
          <CardsView sub="cards" onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>,
    );
    return vi.spyOn(SyncLoop.prototype, 'nextStamp');
  }
  const saved = () => JSON.parse(localStorage.getItem('mkmax:v1')!);

  // Regression: /ship review of clock-and-gear-taps — a fuse tap after a sync used a different step than the button showed
  // Found by /ship on 2026-10-13
  // Value: protects=Use N kards fuses nothing when a sync moved the card to a step that costs more; fails_when=the button
  // doesn't pass the cost it showed, so a dearer step is fused and the Undo label gives the wrong count; why_new=review
  // (Red Team); seam=SyncLoop.nextStamp spied, a grabbed update stands in for the sync; no_claim=a real sync
  it('fuses nothing when a sync moved the card to a dearer step', () => {
    const stamps = renderCards(4, 1);
    const use = screen.getByRole('button', { name: 'Use 1 kard' });
    act(() => {
      update((d) => {
        d.cards[0].fusion = 5;
        d.rarities.find((r) => r.id === 'diamond')!.fusionUpKards = 5;
      });
      use.click();
    });
    expect([saved().cards[0].fusion, saved().rarities.find((r: { id: string }) => r.id === 'diamond').fusionUpKards]).toEqual([5, 5]);
    expect(stamps).toHaveBeenCalledTimes(1);
  });

  // Generated by /ship test coverage audit on 2026-10-13
  // Value: protects=Use N kards fuses nothing when a sync already made that step and the next costs the same; fails_when=
  // the button stops passing the level it showed, so the tap fuses a second level and spends the kards twice; why_new=
  // engine.test.ts covers fuseWithKards' level check, and the test above only a dearer step; seam=SyncLoop.nextStamp
  // spied, a grabbed update stands in for the sync; no_claim=a real sync, Plan's Use button
  it('fuses nothing when a sync already made the step and the next costs the same', () => {
    const stamps = renderCards(4, 10);
    const use = screen.getByRole('button', { name: 'Use 1 kard' });
    act(() => {
      update((d) => {
        const diamond = d.rarities.find((r) => r.id === 'diamond')!;
        d.cards[0].fusion = 5;
        diamond.fusionUpKards = 9;
        diamond.kardsPerLevel[4] = 1; // the next step costs the same 1 kard
      });
      use.click();
    });
    expect([saved().cards[0].fusion, saved().rarities.find((r: { id: string }) => r.id === 'diamond').fusionUpKards]).toEqual([5, 9]);
    expect(stamps).toHaveBeenCalledTimes(1); // the sync stand-in only
  });

  // Value: protects=Delete on a card a sync removed saves nothing and offers no Undo; fails_when=the filter that finds
  // nothing still stamps the save; why_new=review (Red Team); seam=SyncLoop.nextStamp spied, a grabbed update stands in
  // for the sync; no_claim=the other edits on the card, which use the same check
  it('saves nothing for Delete on a card a sync removed', () => {
    const stamps = renderCards(4, 0);
    act(() => screen.getByRole('button', { name: 'Delete' }).click());
    stamps.mockClear();
    const confirm = screen.getByRole('button', { name: 'Tap again to confirm' });
    act(() => {
      update((d) => void (d.cards = []));
      confirm.click();
    });
    expect(stamps).toHaveBeenCalledTimes(1);
  });
});

describe('Cards: levels and Add card on a screen a sync has changed', () => {
  let update!: ReturnType<typeof useStore>['update'];
  function renderWith(cards: ReturnType<typeof defaultState>['cards'], sub: 'cards' | 'towers' = 'cards') {
    const s = defaultState();
    s.cards = cards;
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    render(
      <StoreProvider>
        <PlanProvider>
          <Grab onRender={(store) => (update = store.update)} />
          <CardsView sub={sub} onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>,
    );
    return vi.spyOn(SyncLoop.prototype, 'nextStamp');
  }
  const saved = () => JSON.parse(localStorage.getItem('mkmax:v1')!);

  // Regression: /ship review of stale-screens-and-schedule — a level tap saved the shown level ± 1 over a newer one
  // Found by /ship on 2026-10-13
  // Value: protects=+ and − on a card save nothing when a sync already moved its level, on Cards and on Tower gear;
  // fails_when=the tap saves the level on screen ± 1, so a sync's F5 becomes F4 and that lost level syncs; why_new=review
  // (Red Team); seam=SyncLoop.nextStamp spied, a grabbed update stands in for the sync; no_claim=a real sync
  it('saves nothing for a level tap after a sync moved the card, on Cards and on Tower gear', () => {
    const stamps = renderWith([{ id: 'scorpion', name: 'Scorpion', rarityId: 'diamond', fusion: 3, guest: false }]);
    const raise = screen.getByRole('button', { name: 'Raise level' });
    act(() => {
      update((d) => void (d.cards[0].fusion = 5));
      raise.click();
    });
    const lower = screen.getByRole('button', { name: 'Lower level' });
    act(() => {
      update((d) => void (d.cards[0].fusion = 1));
      lower.click();
    });
    expect(saved().cards[0].fusion).toBe(1);
    expect(stamps).toHaveBeenCalledTimes(2); // the two sync stand-ins only
    cleanup();
    localStorage.clear();
    vi.restoreAllMocks();

    const towerStamps = renderWith([{ id: 'kori', name: 'Kori Blade', rarityId: 'epic', fusion: 1, guest: false, source: 'tower', sourceNote: 'Lin Kuei Tower' }], 'towers');
    const towerRaise = screen.getByRole('button', { name: 'Raise level' });
    act(() => {
      update((d) => void (d.cards[0].fusion = 2));
      towerRaise.click();
    });
    expect(saved().cards[0].fusion).toBe(2);
    expect(towerStamps).toHaveBeenCalledTimes(1);
    // A tap on the level shown still steps it (Epic gear is tracked to F3, so this stays below its goal).
    act(() => screen.getByRole('button', { name: 'Raise level' }).click());
    expect(saved().cards[0].fusion).toBe(3);
  });

  // Value: protects=Add card saves nothing when a sync removed the rarity picked on screen, and keeps the typed name;
  // fails_when=the card is saved under the removed rarity, where it's hidden on every device and can't be deleted;
  // why_new=review (Red Team); seam=SyncLoop.nextStamp spied, a grabbed update stands in for the sync; no_claim=a real sync
  it('saves nothing for Add card when a sync removed its rarity', () => {
    const stamps = renderWith([]);
    const name = screen.getByPlaceholderText('e.g. Sub-Zero, Klassic (name, variant)') as HTMLInputElement;
    fireEvent.change(name, { target: { value: 'Raiden, Dark' } });
    const add = screen.getByRole('button', { name: 'Add' });
    act(() => {
      update((d) => void (d.rarities = d.rarities.filter((r) => r.id !== 'diamond')));
      add.click();
    });
    expect(saved().cards).toEqual([]);
    expect(stamps).toHaveBeenCalledTimes(1);
    expect(name.value).toBe('Raiden, Dark');
  });

  // Regression: /ship review of stale-screens-and-schedule — Add card did nothing at all once a sync removed its rarity
  // Found by /ship on 2026-10-13
  // Value: protects=after a sync removes the picked rarity and the form shows the first rarity, Add saves the card under
  // the rarity shown; fails_when=Add keeps the removed rarity and silently saves nothing on every tap; why_new=review
  // (Red Team, pass 2); seam=a grabbed update stands in for the sync; no_claim=a real sync
  it('adds under the rarity shown once a sync removed the one picked', () => {
    renderWith([]);
    fireEvent.change(screen.getByPlaceholderText('e.g. Sub-Zero, Klassic (name, variant)'), { target: { value: 'Raiden, Dark' } });
    act(() => update((d) => void (d.rarities = d.rarities.filter((r) => r.id !== 'diamond'))));
    act(() => screen.getByRole('button', { name: 'Add' }).click());
    expect(saved().cards.map((c: { name: string; rarityId: string }) => [c.name, c.rarityId])).toEqual([['Raiden, Dark', saved().rarities[0].id]]);
  });
});

// Last in the file: the catalog stays loaded once a test has downloaded it.
describe('Cards: rarity questions on a screen a sync has changed', () => {
  const saved = () => JSON.parse(localStorage.getItem('mkmax:v1')!);

  // Regression: /ship review of stale-screens-and-schedule — the batch Undo label counted cards a sync had answered
  // Found by /ship on 2026-10-13
  // Value: protects=Use the site's for all, after a sync fixed one card, changes and names only the other; fails_when=
  // the label is built from every fix on screen, so Undo names a card this tap didn't change; why_new=review (testing);
  // seam=fetch serves a two-item catalog, a grabbed store stands in for the sync; no_claim=a real sync
  it("names only the cards it changed in Use the site's for all's Undo", async () => {
    vi.stubGlobal('fetch', (url: string) =>
      String(url).endsWith('catalog.json')
        ? Promise.resolve({
            ok: true,
            json: () =>
              Promise.resolve({
                items: [
                  { kind: 'character', name: 'Raiden, Dark', rarity: 'diamond', slug: 'raiden-dark', image: 'x.png' },
                  { kind: 'character', name: 'Kitana, Klassic', rarity: 'diamond', slug: 'kitana-klassic', image: 'y.png' },
                ],
              }),
          })
        : Promise.reject(new Error('offline')),
    );
    const s = defaultState();
    s.cards = [
      { id: 'raiden', name: 'Raiden, Dark', rarityId: 'gold', fusion: 2, guest: false, imageUrl: 'x.png' },
      { id: 'kitana', name: 'Kitana, Klassic', rarityId: 'gold', fusion: 2, guest: false, imageUrl: 'y.png' },
    ];
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    let store!: ReturnType<typeof useStore>;
    render(
      <StoreProvider>
        <PlanProvider>
          <Grab onRender={(x) => (store = x)} />
          <CardsView sub="cards" onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>,
    );
    const all = await screen.findByRole('button', { name: "Use the site's for all" });
    act(() => {
      store.update((d) => void (d.cards[0].rarityId = 'diamond'));
      all.click();
    });
    expect(saved().cards.map((c: { rarityId: string }) => c.rarityId)).toEqual(['diamond', 'diamond']);
    expect(store.lastUndo?.label).toBe('Changed the rarity of Kitana, Klassic');
  });
  // Regression: /review of stale-screens-and-schedule — rarity answers saved again when a sync had already made them
  // Found by /review on 2026-10-13
  // Value: protects=Use the site's and Keep mine save nothing when a sync already gave the card that rarity or that
  // answer; fails_when=they return noChange only for a removed card, so an answer already in place stamps and syncs
  // again; why_new=review (Red Team); seam=fetch serves a one-item catalog, a grabbed update stands in for the sync,
  // SyncLoop.nextStamp spied; no_claim=a real sync, the Undo label
  it("saves nothing for Use the site's or Keep mine when a sync already did it", async () => {
    vi.stubGlobal('fetch', (url: string) =>
      String(url).endsWith('catalog.json')
        ? Promise.resolve({ ok: true, json: () => Promise.resolve({ items: [{ kind: 'character', name: 'Raiden, Dark', rarity: 'diamond', slug: 'raiden-dark', image: 'x.png' }] }) })
        : Promise.reject(new Error('offline')),
    );
    const s = defaultState();
    s.cards = [{ id: 'raiden', name: 'Raiden, Dark', rarityId: 'gold', fusion: 2, guest: false, imageUrl: 'x.png' }];
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    let update!: ReturnType<typeof useStore>['update'];
    render(
      <StoreProvider>
        <PlanProvider>
          <Grab onRender={(store) => (update = store.update)} />
          <CardsView sub="cards" onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>,
    );
    const useSite = await screen.findByRole('button', { name: "Use the site's" });
    const keep = screen.getByRole('button', { name: 'Keep mine' });
    const stamps = vi.spyOn(SyncLoop.prototype, 'nextStamp');
    // All in one act, so both buttons are still on screen for their taps. Each answer is one the other device already
    // gave the other way round: Keep mine after it used the site's rarity, and the site's after it kept the card's.
    act(() => {
      update((d) => void (d.cards[0].rarityId = 'diamond'));
      keep.click();
      update((d) => void Object.assign(d.cards[0], { rarityId: 'gold', keptRarity: 'diamond' }));
      useSite.click();
    });
    expect(saved().cards[0]).toMatchObject({ rarityId: 'gold', keptRarity: 'diamond' });
    expect(stamps).toHaveBeenCalledTimes(2); // the two sync stand-ins only
  });

  // Regression: /review of stale-screens-and-schedule — switching back to Cards reloaded art that had failed to load
  // Found by /review on 2026-10-13
  // Value: protects=a card whose art failed shows its initials again after the Cards tab switches to Tower gear and back;
  // fails_when=the thumbnail resets its failed state each time the hidden page is shown, asking for the dead URL again;
  // why_new=review (adversarial, after the switch to Activity); seam=the img's error event is fired by hand;
  // no_claim=the browser's own image cache
  it('keeps showing initials for art that failed, after switching pages', async () => {
    const s = defaultState();
    s.cards = [{ id: 'kitana', name: 'Kitana', rarityId: 'gold', fusion: 2, guest: false, imageUrl: 'https://example.invalid/kitana.png' }];
    localStorage.setItem('mkmax:v1', JSON.stringify(s));
    const page = (sub: 'cards' | 'towers') => (
      <StoreProvider>
        <PlanProvider>
          <CardsView sub={sub} onSub={() => {}} />
        </PlanProvider>
      </StoreProvider>
    );
    const { container, rerender } = render(page('cards'));
    const art = () => container.querySelector('img[src="https://example.invalid/kitana.png"]');
    act(() => void art()!.dispatchEvent(new Event('error')));
    expect(art()).toBeNull();
    rerender(page('towers'));
    rerender(page('cards'));
    await act(async () => {});
    expect(art()).toBeNull();
  });
});
