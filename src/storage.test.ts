import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { defaultState } from './defaults';
import { UNREADABLE_KEY, discardUnreadable, holdIfNewer, load, loadUnreadable, save, savedByNewerApp, savedText } from './storage';

/** A stand-in for the browser's localStorage, which Vitest's Node environment doesn't have. */
class MemoryStorage {
  items = new Map<string, string>();
  getItem(k: string) {
    return this.items.get(k) ?? null;
  }
  setItem(k: string, v: string) {
    this.items.set(k, v);
  }
  removeItem(k: string) {
    this.items.delete(k);
  }
}

let storage: MemoryStorage;
const g = globalThis as unknown as { localStorage?: unknown };
const syncConfig = (baseUpdatedAt: number) => JSON.stringify({ token: 't', gistId: 'g1', baseUpdatedAt });

beforeEach(() => {
  storage = new MemoryStorage();
  g.localStorage = storage;
});
afterEach(() => {
  delete g.localStorage;
});

describe('loading the saved data', () => {
  it('keeps a save that can’t be read and starts fresh', () => {
    storage.setItem('mkmax:v1', '{"cards": [');
    expect(load()).toEqual(defaultState());
    expect(storage.getItem(UNREADABLE_KEY)).toBe('{"cards": [');
    expect(loadUnreadable()).toBe('{"cards": [');
  });

  it('keeps a save that loads as JSON but isn’t one MK Max can read', () => {
    storage.setItem('mkmax:v1', '{"cards": 3}');
    expect(load()).toEqual(defaultState());
    expect(loadUnreadable()).toBe('{"cards": 3}');
  });

  it('with sync on, forgets what was agreed so the first sync downloads the gist’s copy', () => {
    storage.setItem('mkmax:v1', 'not json');
    storage.setItem('mkmax:sync', syncConfig(5000));
    load();
    expect(JSON.parse(storage.getItem('mkmax:sync')!).baseUpdatedAt).toBe(0);
  });

  // Generated by /ship TODO fix on 2026-10-19
  // Value: protects=a save from a newer version is shown but never saved over, kept nowhere else, and leaves sync's agreed
  // stamp alone; fails_when=load normalizes and the first save writes the older reading back (dropping the Maxed record
  // and fields it doesn't know); why_new=TODOS.md P2 (older copy of the app on the same device); seam=none;
  // no_claim=the store refusing changes and pausing sync (store.test.tsx)
  it('shows a save from a newer version without ever saving over it', () => {
    const raw = JSON.stringify({ ...defaultState(), version: 99, maxed: [{ name: 'Kori Blade', rarityId: 'epic' }], fromTheFuture: true, updatedAt: 7000 });
    storage.setItem('mkmax:v1', raw);
    storage.setItem('mkmax:sync', syncConfig(5000));
    const shown = load();
    save(shown);
    expect([savedByNewerApp(), shown.maxed, storage.getItem('mkmax:v1'), loadUnreadable(), JSON.parse(storage.getItem('mkmax:sync')!).baseUpdatedAt]).toEqual([
      true,
      [{ name: 'Kori Blade', rarityId: 'epic' }],
      raw,
      null,
      5000,
    ]);
  });

  // Generated by /ship TODO fix on 2026-10-19
  // Value: protects=a newer save this copy can't read either stays where it is for the newer build, rather than being
  // moved aside as unreadable and replaced by fresh data; fails_when=the unreadable path runs for it, so the updated app
  // finds a fresh save; why_new=TODOS.md P2; seam=none; no_claim=reading a newer save that does parse (test above)
  it('leaves a newer save it can’t read where it is', () => {
    storage.setItem('mkmax:v1', '{"version": 99, "cards": 3}');
    storage.setItem('mkmax:sync', syncConfig(5000));
    save(load());
    expect([savedByNewerApp(), storage.getItem('mkmax:v1'), loadUnreadable(), JSON.parse(storage.getItem('mkmax:sync')!).baseUpdatedAt]).toEqual([
      true,
      '{"version": 99, "cards": 3}',
      null,
      5000,
    ]);
  });

  // Generated by /ship TODO fix on 2026-10-19
  // Value: protects=another tab's save holds this one only when it's this app's save from a newer version, and from then
  // on this tab writes nothing, and a broken (non-JSON) save throws rather than being read past; fails_when=other keys or
  // older saves start a hold, broken text is quietly treated as not newer, or a held tab still saves over the newer data;
  // why_new=review of the TODOS.md P2 fix (a tab already open isn't held by load); changed by /ship review fixes on
  // 2026-10-19 (gate decision run 6: broken text throws); seam=none; no_claim=the store's storage listener (store.test.tsx)
  it('holds from another tab’s newer save, and only that', () => {
    storage.setItem('mkmax:v1', JSON.stringify(defaultState()));
    load();
    const newer = JSON.stringify({ ...defaultState(), version: 99 });
    expect([
      holdIfNewer('mkmax:sync', newer),
      holdIfNewer('mkmax:v1', JSON.stringify(defaultState())),
      holdIfNewer('mkmax:v1', null),
    ]).toEqual([false, false, false]);
    expect(() => holdIfNewer('mkmax:v1', '{"version": 99')).toThrow(SyntaxError);
    expect(savedByNewerApp()).toBe(false);
    storage.setItem('mkmax:v1', newer);
    expect(holdIfNewer('mkmax:v1', newer)).toBe(true);
    save(defaultState());
    expect([savedByNewerApp(), storage.getItem('mkmax:v1'), savedText()]).toEqual([true, newer, newer]);
  });

  it('with sync off, saves no sync settings', () => {
    storage.setItem('mkmax:v1', 'not json');
    load();
    expect(storage.getItem('mkmax:sync')).toBeNull();
  });

  it('leaves a good save and the sync settings alone', () => {
    const saved = { ...defaultState(), updatedAt: 4000 };
    storage.setItem('mkmax:v1', JSON.stringify(saved));
    storage.setItem('mkmax:sync', syncConfig(4000));
    expect(load().updatedAt).toBe(4000);
    expect(loadUnreadable()).toBeNull();
    expect(JSON.parse(storage.getItem('mkmax:sync')!).baseUpdatedAt).toBe(4000);
    // Extended by /ship TODO fix on 2026-10-19: saves as usual, though the tests above held a newer save on their load.
    save({ ...saved, updatedAt: 4100 });
    expect([savedByNewerApp(), JSON.parse(storage.getItem('mkmax:v1')!).updatedAt]).toEqual([false, 4100]);
  });

  it('starts fresh without touching anything when storage can’t be read at all', () => {
    storage.setItem('mkmax:sync', syncConfig(5000));
    storage.getItem = (k: string) => {
      if (k === 'mkmax:v1') throw new Error('blocked');
      return MemoryStorage.prototype.getItem.call(storage, k);
    };
    expect(load()).toEqual(defaultState());
    expect(storage.items.has(UNREADABLE_KEY)).toBe(false);
    expect(JSON.parse(storage.items.get('mkmax:sync')!).baseUpdatedAt).toBe(5000);
  });

  it('discarding removes the kept copy', () => {
    storage.setItem(UNREADABLE_KEY, 'old');
    discardUnreadable();
    expect(loadUnreadable()).toBeNull();
  });
});
